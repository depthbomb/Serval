using System.Security.Cryptography;
using Serval.Http;
using Serval.Http.Constants;
using Serval.Routing;

namespace Serval.Sample.Files;

[Controller]
public sealed class FilesController : ControllerBase
{
    [Get("/")]
    public ValueTask<IActionResult> IndexAsync(RequestContext context) => TextAsync("""
                                                                                    Files and custom results
                                                                                    GET /sample-data.json        Static JSON with ETag and Last-Modified
                                                                                    Send If-None-Match with the returned ETag to get 304.
                                                                                    HEAD /sample-data.json       File metadata without downloading the body
                                                                                    GET /downloads/report        Explicit attachment outside the public directory
                                                                                    GET /exports/report          CSV generated by a custom IActionResult
                                                                                    POST /uploads/digest         Raw body -> byte count and SHA-256 (64 KiB limit)
                                                                                    Uploaded bytes are hashed in memory and never saved.
                                                                                    """);

    [Get("/downloads/{name:alpha}")]
    public ValueTask<IActionResult> DownloadAsync(RequestContext context)
    {
        // Resolve an application-owned name rather than combining an untrusted path.
        AbortUnless(context.RouteValues["name"] == "report", StatusCodes.NotFound, "Unknown download.");
        return FileAsync(Path.Combine(AppContext.BaseDirectory, "Downloads", "report.csv"), "text/csv; charset=utf-8", "report.csv");
    }

    [Get("/exports/report")]
    public ValueTask<IActionResult> ExportAsync(RequestContext context)
        => ValueTask.FromResult<IActionResult>(new CsvResult([
            ["Product", "Description"],
            ["Serval", "HTTP, routing, and middleware"],
            ["Example", "A quoted \"value\" and a\nsecond line"],
        ]));

    [Post("/uploads/digest")]
    public async ValueTask<IActionResult> DigestAsync(RequestContext context)
    {
        var bytes = await context.Request.ReadBodyAsync(context.RequestAborted);
        return Json(new { length = bytes.Length, sha256 = Convert.ToHexString(SHA256.HashData(bytes)) });
    }
}
