using Microsoft.CodeAnalysis.CSharp;
using System.Text;

namespace Serval.Vite.Generators;

internal static class ViteEmitter
{
    public static string Emit(Dictionary<string, ManifestChunk> chunks,
                              string                            generatedNamespace,
                              string                            className,
                              string                            baseUrl,
                              CancellationToken                 cancellationToken,
                              bool                              development = false)
    {
        // Sort once for reproducible output; dependency traversal needs constant-time key lookups.
        var keys = chunks.Keys.ToArray();
        Array.Sort(keys, StringComparer.Ordinal);

        var urlPrefix    = baseUrl.Length == 0 ? "" : baseUrl.TrimEnd('/') + "/";
        // Flat manifests mostly visit each file once. Imported chunks benefit from reusing resolved URL strings.
        var resolvedUrls = chunks.Values.Any(chunk => chunk.Imports.Length != 0) ? new Dictionary<string, string>(StringComparer.Ordinal) : null;
        var source       = new StringBuilder();
        source.Append("// <auto-generated/>\n#nullable enable\n");
        if (generatedNamespace.Length != 0)
        {
            source.Append("namespace ").Append(generatedNamespace).Append(";\n\n");
        }

        source.Append("""
                      /// <summary>Asset URLs and entry dependencies generated for the selected Vite build mode.</summary>
                      /// <remarks>
                      /// Keys are exact and case-sensitive. Production uses manifest keys; development uses ViteDevEntries and
                      /// ViteDevAssets source paths. URLs need normal HTML attribute encoding.
                      /// </remarks>
                      public static class
                      """).Append(' ').Append(className).Append("\n{\n");
        source.Append("    /// <summary>Whether this assembly was built with ViteDevelopment enabled.</summary>\n")
              .Append("    public static bool IsDevelopment => ").Append(development ? "true" : "false").Append(";\n\n");
        source.Append("""
                          /// <summary>Known source keys mapped to URLs: manifest outputs in production, declared source files in development.</summary>
                          public static global::System.Collections.Generic.IReadOnlyDictionary<string, string> Urls => _urls;

                          /// <summary>Manifest entry points, or ViteDevEntries in development, with their precomputed asset lists.</summary>
                          public static global::System.Collections.Generic.IReadOnlyDictionary<string, global::Serval.Vite.ViteEntry> Entries => _entries;

                          private static readonly global::System.Collections.Frozen.FrozenDictionary<string, string> _urls =
                              global::System.Collections.Frozen.FrozenDictionary.ToFrozenDictionary(
                                  new global::System.Collections.Generic.Dictionary<string, string>(global::System.StringComparer.Ordinal)
                                  {
                      """).Append('\n');
        foreach (var key in keys)
        {
            cancellationToken.ThrowIfCancellationRequested();
            source.Append("                [").Append(Literal(key)).Append("] = ").Append(Literal(ViteEntryBuilder.ResolveUrl(urlPrefix, chunks[key].File, resolvedUrls))).Append(",\n");
        }

        source.Append("            }, global::System.StringComparer.Ordinal);\n\n");
        source.Append("""
                          private static readonly global::System.Collections.Frozen.FrozenDictionary<string, global::Serval.Vite.ViteEntry> _entries =
                              global::System.Collections.Frozen.FrozenDictionary.ToFrozenDictionary(
                                  new global::System.Collections.Generic.Dictionary<string, global::Serval.Vite.ViteEntry>(global::System.StringComparer.Ordinal)
                                  {
                      """).Append('\n');
        // Shared chunks repeat across entries. Escape each URL once instead of rebuilding its C# literal per page.
        var literals = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var key in keys)
        {
            cancellationToken.ThrowIfCancellationRequested();
            if (!chunks[key].IsEntry)
            {
                continue;
            }

            // Vite transforms source modules and handles their CSS imports. Loading built dependencies would bypass HMR.
            var entry = development
                ? new EntryAssets([urlPrefix + "@vite/client", urlPrefix + chunks[key].File + "?import"], [], [])
                : ViteEntryBuilder.Build(chunks, key, urlPrefix, resolvedUrls, cancellationToken);
            source.Append("                [").Append(Literal(key)).Append("] = new global::Serval.Vite.ViteEntry(\n                    ");
            AppendArray(source, entry.Scripts, literals);
            source.Append(",\n                    ");
            AppendArray(source, entry.Stylesheets, literals);
            source.Append(",\n                    ");
            AppendArray(source, entry.ModulePreloads, literals);
            source.Append("),\n");
        }

        source.Append("            }, global::System.StringComparer.Ordinal);\n\n");
        source.Append("""
                          /// <summary>Gets the URL for an exact source key.</summary>
                          /// <param name="key">The source key, such as src/main.ts or src/images/logo.svg.</param>
                          /// <returns>The build output URL, or the development source URL, including the configured base URL.</returns>
                          /// <exception cref="global::System.ArgumentNullException">The key is null.</exception>
                          /// <exception cref="global::System.Collections.Generic.KeyNotFoundException">The key is not in the manifest or declared development paths.</exception>
                          public static string GetUrl(string key) => _urls[key];

                          /// <summary>Looks up an asset without throwing for an unknown key.</summary>
                          /// <param name="key">The exact, case-sensitive manifest or declared development key.</param>
                          /// <param name="url">The output URL when found; otherwise null.</param>
                          /// <returns>Whether the generated lookups contain the key.</returns>
                          /// <exception cref="global::System.ArgumentNullException">The key is null.</exception>
                          public static bool TryGetUrl(string key, [global::System.Diagnostics.CodeAnalysis.NotNullWhen(true)] out string? url) => _urls.TryGetValue(key, out url);

                          /// <summary>Gets the precomputed dependencies for one entry point.</summary>
                          /// <param name="key">An exact manifest entry key, or a source path declared in ViteDevEntries.</param>
                          /// <returns>A shared immutable entry; repeated calls do not allocate dependency lists.</returns>
                          /// <remarks>Development scripts include the Vite client followed by the source module. CSS imports and dependencies are handled by Vite.</remarks>
                          /// <exception cref="global::System.ArgumentNullException">The key is null.</exception>
                          /// <exception cref="global::System.Collections.Generic.KeyNotFoundException">The key is unknown or is not an entry point.</exception>
                          public static global::Serval.Vite.ViteEntry GetEntry(string key) => _entries[key];

                          /// <summary>Looks up an entry without throwing for unknown or non-entry keys.</summary>
                          /// <param name="key">The exact, case-sensitive manifest or declared development key.</param>
                          /// <param name="entry">The entry when found; otherwise null.</param>
                          /// <returns>Whether the key identifies an entry point.</returns>
                          /// <exception cref="global::System.ArgumentNullException">The key is null.</exception>
                          public static bool TryGetEntry(string key, [global::System.Diagnostics.CodeAnalysis.NotNullWhen(true)] out global::Serval.Vite.ViteEntry? entry) => _entries.TryGetValue(key, out entry);
                      }
                      """).Append('\n');
        return source.ToString();
    }

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, true);

    private static void AppendArray(StringBuilder source, string[] values, Dictionary<string, string> literals)
    {
        if (values.Length == 0)
        {
            source.Append("global::System.Array.Empty<string>()");
            return;
        }

        source.Append("new string[] { ");
        for (var index = 0; index < values.Length; index++)
        {
            if (index != 0)
            {
                source.Append(", ");
            }

            var value = values[index];
            if (!literals.TryGetValue(value, out var literal))
            {
                literal = Literal(value);
                literals.Add(value, literal);
            }

            source.Append(literal);
        }

        source.Append(" }");
    }
}
