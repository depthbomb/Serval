using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;
using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;
using Serval.Savanna.Compiler.Html;
using Serval.Savanna.Compiler.Syntax;

namespace Serval.Savanna.Compiler.CodeGeneration;

internal sealed class SavannaEmitter
{
    private          int               _literal;
    private          int               _temporary;
    private readonly CancellationToken _cancellationToken;

    private readonly        IReadOnlyList<SavannaDocument>               _chain;
    private readonly        string                                    _className;
    private readonly        StringBuilder                             _code = new();
    private readonly        List<SavannaDiagnostic>                      _diagnostics;
    private readonly        List<SavannaSourceMapping>                   _mappings = [];
    private readonly        string                                    _namespace;
    private readonly        IReadOnlyDictionary<string, SavannaDocument> _views;
    private static readonly Regex                                     AttributePrefix = new(@"\s+[^\s=<>/]+\s*=\s*['""]$", RegexOptions.CultureInvariant);
    private static readonly HashSet<string> BooleanAttributes = new(StringComparer.Ordinal)
        { "allowfullscreen", "async", "autofocus", "autoplay", "checked", "controls", "default", "defer", "disabled", "formnovalidate", "inert", "ismap", "itemscope", "loop", "multiple", "muted", "nomodule", "novalidate", "open", "playsinline", "readonly", "required", "reversed", "selected" };

    private SavannaEmitter(IReadOnlyList<SavannaDocument>               chain,
                        IReadOnlyDictionary<string, SavannaDocument> views,
                        string                                    generatedNamespace,
                        List<SavannaDiagnostic>                      diagnostics,
                        CancellationToken                         cancellationToken)
    {
        _chain             = chain;
        _views             = views;
        _namespace         = generatedNamespace;
        _diagnostics       = diagnostics;
        _cancellationToken = cancellationToken;
        using var hash = SHA256.Create();
        _className = "__Savanna_" + BitConverter.ToString(hash.ComputeHash(Encoding.UTF8.GetBytes(chain[0].Name))).Replace("-", "");
    }

    public static SavannaGeneratedSource Emit(IReadOnlyList<SavannaDocument>               chain,
                                           IReadOnlyDictionary<string, SavannaDocument> views,
                                           string                                    generatedNamespace,
                                           List<SavannaDiagnostic>                      diagnostics,
                                           CancellationToken                         cancellationToken)
    {
        var emitter = new SavannaEmitter(chain, views, generatedNamespace, diagnostics, cancellationToken);
        emitter.Generate();
        return new SavannaGeneratedSource(emitter._className + ".g.cs", emitter._code.ToString(), [.. emitter._mappings]);
    }

    public static void ValidateMarkup(SavannaDocument document, List<SavannaDiagnostic> diagnostics)
    {
        ValidateBody(document, document.Body, diagnostics);
        foreach (var block in document.Blocks)
        {
            ValidateBody(document, block.Body, diagnostics);
        }
    }

    private void Generate()
    {
        _code.AppendLine("// <auto-generated/>").AppendLine("#nullable enable");
        var savanna = _chain[0];
        ValidateRenderedBody(_chain[_chain.Count - 1], _chain.Count - 1, _chain[_chain.Count - 1].Body, null, new SavannaHtmlContext(), new SavannaHtmlControlFlow());
        Namespace(savanna);
        var identifiers = SavannaCompiler.IdentifierPath(savanna.Name).Split('.');
        _code.AppendLine("    public static partial class Views").AppendLine("    {");
        foreach (var identifier in identifiers.Take(identifiers.Length - 1))
        {
            _code.Append("        public static partial class ").Append(identifier).AppendLine().AppendLine("        {");
        }

        _code.Append("        public static global::Serval.Savanna.SavannaView<").Append(savanna.Model).Append("> ").Append(identifiers.Last())
             .Append(" { get; } = new(").Append(SymbolDisplay.FormatLiteral(savanna.Name, true)).Append(", ").Append(_className).Append(".RenderAsync, ")
             .Append(_className).AppendLine(".RenderPartialAsync);");
        foreach (var _ in identifiers.Take(identifiers.Length - 1))
        {
            _code.AppendLine("        }");
        }

        _code.AppendLine("    }");
        _code.Append("    internal sealed partial class ").AppendLine(_className).AppendLine("    {")
             .AppendLine("        private readonly global::Serval.Savanna.SavannaRenderContext __context;");
        _code.AppendLine("        private global::Serval.Routing.IUrlGenerator Urls => __context.Urls;");
        _code.Append("        private ").Append(_className).Append("(global::Serval.Savanna.SavannaWriter writer, ").Append(savanna.Model)
             .AppendLine(" model, global::Serval.Savanna.SavannaRenderContext context)")
             .AppendLine("        {").AppendLine("            __context = context;").AppendLine("            __model0 = model;");
        for (var index = 0; index < _chain.Count - 1; index++)
        {
            _code.Append("            __Initialize").Append(index).AppendLine("();");
        }

        _code.AppendLine("        }");
        _code.Append("        internal static global::System.Threading.Tasks.ValueTask RenderAsync(global::Serval.Savanna.SavannaWriter writer, ")
             .Append(savanna.Model).AppendLine(" model, global::Serval.Savanna.SavannaRenderContext context)")
             .Append("            => new ").Append(_className).AppendLine("(writer, model, context).__BodyAsync(writer, __viewComment);");
        _code.Append("        internal static global::System.Threading.Tasks.ValueTask RenderPartialAsync(global::Serval.Savanna.SavannaWriter writer, ")
             .Append(savanna.Model).AppendLine(" model, global::Serval.Savanna.SavannaRenderContext context)")
             .Append("            => new ").Append(_className).AppendLine("(writer, model, context).__BodyAsync(writer, __partialComment);");
        CommentField("__viewComment", SavannaComments.Template("view", _chain));
        CommentField("__partialComment", SavannaComments.Template("partial", _chain));
        _code.AppendLine("    }").AppendLine("}");

        // Separate namespace blocks give each layout its own using directives and model type.
        for (var index = 0; index < _chain.Count; index++)
        {
            _cancellationToken.ThrowIfCancellationRequested();
            var document = _chain[index];
            ValidateMarkup(document, _diagnostics);
            Namespace(document);
            _code.Append("    internal sealed partial class ").AppendLine(_className).AppendLine("    {");
            Mapped(document, document.ModelSpan, "        private ", document.Model, " __model" + index + " = default!;");
            if (document.Parent is { } parent)
            {
                _code.Append("        private void __Initialize").Append(index).AppendLine("()").AppendLine("        {");
                Locals(index);
                Mapped(document, parent.ArgumentSpan, "            __model" + (index + 1) + " = ", parent.Argument, ";");
                _code.AppendLine("        }");
            }
            else
            {
                Method(document, index, "__BodyAsync", document.Body, null);
            }

            foreach (var block in document.Blocks)
            {
                if (!block.Required)
                {
                    Method(document, index, BlockMethod(index, block.Name), block.Body, block.Name);
                }
            }

            _code.AppendLine("    }").AppendLine("}");
        }

        _code.AppendLine("#line default");
    }

    private void Namespace(SavannaDocument document)
    {
        _code.AppendLine("#line default").Append("namespace ").AppendLine(_namespace).AppendLine("{")
             .AppendLine("    using System;").AppendLine("    using System.Linq;").AppendLine("    using System.Collections.Generic;")
             .AppendLine("    using System.Threading;").AppendLine("    using System.Threading.Tasks;").AppendLine("    using Serval.Savanna;");
        foreach (var name in document.Usings.Where(name => name is not ("System" or "System.Linq" or "System.Collections.Generic" or "System.Threading" or "System.Threading.Tasks" or "Serval.Savanna")))
        {
            _code.Append("    using ").Append(name).AppendLine(";");
        }
    }

    private void Locals(int index)
    {
        _code.Append("            var Model = __model").Append(index).AppendLine(";")
             .AppendLine("            var Context = __context;")
             .AppendLine("            _ = Model;").AppendLine("            _ = Context;");
    }

    private void Method(SavannaDocument document, int index, string name, IReadOnlyList<SavannaNode> nodes, string? currentBlock)
    {
        var body = name == "__BodyAsync";
        _code.Append("        private async global::System.Threading.Tasks.ValueTask ").Append(name).Append("(global::Serval.Savanna.SavannaWriter __writer")
             .AppendLine(body ? ", byte[] __comment)" : ")").AppendLine("        {");
        Locals(index);
        // The body writes its compiled header directly, without an extra async wrapper for each partial.
        _code.AppendLine(body
            ? "            await __writer.WriteLiteralAsync(__comment, Context.CancellationToken);"
            : "            await global::System.Threading.Tasks.ValueTask.CompletedTask;");
        var html           = new SavannaHtmlContext();
        var minified       = SavannaHtmlMinifier.Minify(nodes);
        var literals       = new List<(string Name, string Text, string Condition)>();
        var comments       = new List<(string Name, string Type, string Condition)>();
        var attributes     = new Dictionary<string, string>(StringComparer.Ordinal);
        var loops          = new Stack<int>();
        var calls          = new Stack<(SavannaNode Node, int Id, string Writer)>();
        var slots          = new Stack<(bool Definition, string Writer, int CallDepth)>();
        var builds         = new Stack<string>();
        var buildCondition = "";
        var writer         = "__writer";
        var removeQuote    = false;
        for (var nodeIndex = 0; nodeIndex < nodes.Count; nodeIndex++)
        {
            _cancellationToken.ThrowIfCancellationRequested();
            var node         = nodes[nodeIndex];
            var preserveCall = !node.Paired && minified.Preserved.Contains(node) && node.Kind is SavannaNodeKind.Include or SavannaNodeKind.Component or SavannaNodeKind.Block or SavannaNodeKind.Parent;
            if (preserveCall)
            {
                _code.Append("            using (").Append(writer).AppendLine(".PreserveWhitespace())").AppendLine("            {");
            }

            switch (node.Kind)
            {
                case SavannaNodeKind.Text:
                    if (calls.Count > 0 && (slots.Count == 0 || slots.Peek().CallDepth < calls.Count))
                    {
                        break;
                    }

                    var literal  = "__literal" + _literal++;
                    var original = ReadText(nodes, ref nodeIndex);
                    var compact  = minified.Text[node];
                    html.Read(original);
                    if (removeQuote)
                    {
                        original    = original.Substring(1);
                        compact     = compact.Substring(1);
                        removeQuote = false;
                    }

                    if (nodeIndex + 2 < nodes.Count && nodes[nodeIndex + 1].Kind == SavannaNodeKind.Expression && IsFullAttribute(html, nodes[nodeIndex + 2]))
                    {
                        // Let the runtime own the whole attribute so null and false can omit its name and quotes too.
                        original = AttributePrefix.Replace(original, "");
                        compact  = AttributePrefix.Replace(compact, "");
                    }

                    literals.Add((literal, compact, buildCondition));
                    var selection = literal;
                    if (compact != original)
                    {
                        literals.Add((literal + "Original", original, buildCondition));
                        selection = writer + ".PreservesWhitespace ? " + literal + "Original : " + literal;
                    }

                    var indentationOnly = string.IsNullOrWhiteSpace(original);
                    if (indentationOnly)
                    {
                        // Indentation after a compile-time jump is harmless, even in a warnings-as-errors build.
                        _code.AppendLine("#pragma warning disable CS0162");
                    }

                    _code.Append("            await ").Append(writer).Append(".WriteLiteralAsync(").Append(selection).AppendLine(", Context.CancellationToken);");
                    if (indentationOnly)
                    {
                        _code.AppendLine("#pragma warning restore CS0162");
                    }

                    break;
                case SavannaNodeKind.Expression:
                    var writeMethod   = html.Interpolation == SavannaInterpolationContext.Url ? "WriteUrlAsync" : "WriteValueAsync";
                    var attributeName = "";
                    if (nodeIndex > 0 && nodes[nodeIndex - 1].Kind == SavannaNodeKind.Text && nodeIndex + 1 < nodes.Count && IsFullAttribute(html, nodes[nodeIndex + 1]))
                    {
                        if (!attributes.TryGetValue(html.AttributeSpelling, out var attributeField))
                        {
                            attributeField = "__attribute" + _temporary++;
                            attributes.Add(html.AttributeSpelling, attributeField);
                        }

                        attributeName = attributeField + ", ";
                        writeMethod = html.Interpolation == SavannaInterpolationContext.Url ? "WriteUrlAttributeAsync"
                            : BooleanAttributes.Contains(html.AttributeName)             ? "WriteBooleanAttributeAsync" : "WriteAttributeAsync";
                        removeQuote = true;
                    }

                    Mapped(document, node.Span, "            await " + writer + "." + writeMethod + "(" + attributeName + "(", node.Value, "), Context);");
                    break;
                case SavannaNodeKind.Html:
                    Mapped(document, node.Span, "            await " + writer + ".WriteHtmlAsync((", node.Value, "), Context);");
                    break;
                case SavannaNodeKind.Include:
                case SavannaNodeKind.Component:
                    if (node.Paired)
                    {
                        var id = _temporary++;
                        calls.Push((node, id, writer));
                        _code.AppendLine("            {").Append("            var __slots").Append(id)
                             .AppendLine(" = new global::System.Collections.Generic.Dictionary<string, global::Serval.Savanna.SavannaRenderFragment>(global::System.StringComparer.Ordinal);");
                    }
                    else
                    {
                        RenderCall(node, "Context.WithSlots(global::Serval.Savanna.SavannaSlots.Empty)");
                    }

                    break;
                case SavannaNodeKind.EndInclude:
                case SavannaNodeKind.EndComponent:
                    var call = calls.Pop();
                    if (minified.Preserved.Contains(call.Node))
                    {
                        _code.Append("            using (").Append(writer).AppendLine(".PreserveWhitespace())");
                    }

                    RenderCall(call.Node, "Context.WithSlots(new global::Serval.Savanna.SavannaSlots(__slots" + call.Id + "))");
                    _code.AppendLine("            }");
                    break;
                case SavannaNodeKind.Slot:
                    // Nested calls switch writers only inside supplied fragments; restore the caller's writer afterward.
                    var definition = calls.Count > 0 && (slots.Count == 0 || slots.Peek().CallDepth < calls.Count);
                    slots.Push((definition, writer, calls.Count));
                    if (definition)
                    {
                        if (!node.Paired)
                        {
                            SavannaCompiler.Error(document, node.Span, "A supplied slot must have a body.", _diagnostics);
                        }

                        var id = _temporary++;
                        _code.Append("            __slots").Append(calls.Peek().Id).Append(".Add(").Append(SymbolDisplay.FormatLiteral(node.Value, true))
                             .Append(", async (__slotWriter").Append(id).Append(", __slotContext").Append(id).AppendLine(") => {")
                             .AppendLine("            await global::System.Threading.Tasks.ValueTask.CompletedTask;");
                        writer = "__slotWriter" + id;
                    }
                    else
                    {
                        var slotName = SymbolDisplay.FormatLiteral(node.Value, true);
                        if (node.Paired)
                        {
                            _code.Append("            if (Context.Slots.Contains(").Append(slotName).AppendLine(")) {");
                        }

                        if (minified.Preserved.Contains(node))
                        {
                            _code.Append("            using (").Append(writer).AppendLine(".PreserveWhitespace())");
                        }

                        _code.Append("            await Context.Slots.RenderAsync(").Append(slotName).Append(", ").Append(writer)
                             .Append(", Context, ").Append(node.Required ? "true" : "false").AppendLine(");");
                        if (node.Paired)
                        {
                            _code.AppendLine("            } else {");
                        }
                    }

                    if (!node.Paired)
                    {
                        slots.Pop();
                    }

                    break;
                case SavannaNodeKind.EndSlot:
                    var slot = slots.Pop();
                    writer = slot.Writer;
                    _code.AppendLine(slot.Definition ? "            });" : "            }");
                    break;
                case SavannaNodeKind.Let:
                    Mapped(document, node.ArgumentSpan, "            var " + node.Value + " = (", node.Argument, ");");
                    _code.Append("            _ = ").Append(node.Value).AppendLine(";");
                    break;
                case SavannaNodeKind.Json:
                    Mapped(document, node.ArgumentSpan, "            await " + writer + ".WriteJsonAsync(" + SymbolDisplay.FormatLiteral(node.Value, true) + ", (", node.Argument, "), Context);");
                    break;
                case SavannaNodeKind.Whitespace:
                    _code.Append("            using (").Append(writer).AppendLine(".PreserveWhitespace()) {");
                    break;
                case SavannaNodeKind.EndWhitespace:
                    _code.AppendLine("            }");
                    break;
                case SavannaNodeKind.Block:
                    var selected = FindBlock(0, node.Value);
                    _code.Append("            await ").Append(BlockMethod(selected, node.Value)).Append('(').Append(writer).AppendLine(");");
                    break;
                case SavannaNodeKind.Parent:
                    var parent = FindBlock(index + 1, currentBlock!);
                    if (parent < 0)
                    {
                        SavannaCompiler.Error(document, node.Span, "This block has no parent implementation.", _diagnostics);
                    }
                    else
                    {
                        _code.Append("            await ").Append(BlockMethod(parent, currentBlock!)).Append('(').Append(writer).AppendLine(");");
                    }

                    break;
                case SavannaNodeKind.If:
                case SavannaNodeKind.Unless:
                    Mapped(document, node.Span, node.Kind == SavannaNodeKind.Unless ? "            if (!(" : "            if (", node.Value,
                        node.Kind                         == SavannaNodeKind.Unless ? "))" : ")");
                    _code.AppendLine("            {");
                    break;
                case SavannaNodeKind.Switch:
                    Mapped(document, node.Span, "            switch (", node.Value, ")");
                    _code.AppendLine("            {");
                    break;
                case SavannaNodeKind.Case:
                    Mapped(document, node.Span, "            case ", node.Value, ":");
                    break;
                case SavannaNodeKind.Default:
                    _code.AppendLine("            default:");
                    break;
                case SavannaNodeKind.Break:
                case SavannaNodeKind.Continue:
                    if (node.Value.Length > 0)
                    {
                        Mapped(document, node.Span, "            if (", node.Value, ")");
                        _code.AppendLine("            {");
                    }

                    _code.AppendLine(node.Kind == SavannaNodeKind.Break ? "            break;" : "            continue;");
                    if (node.Value.Length > 0)
                    {
                        _code.AppendLine("            }");
                    }

                    break;
                case SavannaNodeKind.EndSwitch:
                    _code.AppendLine("            }");
                    break;
                case SavannaNodeKind.Debug:
                case SavannaNodeKind.Release:
                    var symbol = node.Kind == SavannaNodeKind.Debug ? "DEBUG" : "!DEBUG";
                    builds.Push(buildCondition);
                    // Nested equal guards add no restriction; opposite guards can never be active together.
                    buildCondition = buildCondition.Length == 0 || buildCondition == symbol ? symbol : "false";
                    _code.Append("#if ").AppendLine(symbol).AppendLine("            {");
                    break;
                case SavannaNodeKind.EndBuild:
                    _code.AppendLine("            }").AppendLine("#endif");
                    buildCondition = builds.Pop();
                    break;
                case SavannaNodeKind.ElseIf:
                    _code.AppendLine("            }");
                    Mapped(document, node.Span, "            else if (", node.Value, ")");
                    _code.AppendLine("            {");
                    break;
                case SavannaNodeKind.Else:
                    _code.AppendLine("            }").AppendLine("            else").AppendLine("            {");
                    break;
                case SavannaNodeKind.For:
                case SavannaNodeKind.ForEach:
                case SavannaNodeKind.AwaitForEach:
                    var keyword = node.Kind switch
                    {
                        SavannaNodeKind.For          => "for",
                        SavannaNodeKind.AwaitForEach => "await foreach",
                        _                         => "foreach",
                    };
                    var loopId = _temporary++;
                    loops.Push(loopId);
                    _code.Append("            var __any").Append(loopId).AppendLine(" = false;");
                    if (node.Argument.Length > 0)
                    {
                        Mapped(document, node.Span, "            " + keyword + " (var ", node.Value, " in");
                        Mapped(document, node.ArgumentSpan, "                ", node.Argument, ")");
                    }
                    else
                    {
                        var parentheses = node.Value.TrimStart().StartsWith("(", StringComparison.Ordinal);
                        Mapped(document, node.Span, "            " + keyword + (parentheses ? " " : " ("), node.Value, parentheses ? "" : ")");
                    }

                    _code.AppendLine("            {").Append("                __any").Append(loopId).AppendLine(" = true;")
                         .AppendLine("                Context.CancellationToken.ThrowIfCancellationRequested();");
                    break;
                case SavannaNodeKind.Empty:
                    _code.AppendLine("            }").Append("            if (!__any").Append(loops.Peek()).AppendLine(") {");
                    break;
                case SavannaNodeKind.EndIf:
                    _code.AppendLine("            }");
                    break;
                case SavannaNodeKind.EndFor:
                case SavannaNodeKind.EndForEach:
                    _code.AppendLine("            }");
                    _code.Append("            _ = __any").Append(loops.Pop()).AppendLine(";");
                    break;
            }

            if (preserveCall)
            {
                _code.AppendLine("            }");
            }
        }

        void RenderCall(SavannaNode callNode, string context)
        {
            if (callNode.Kind == SavannaNodeKind.Include)
            {
                var target = SavannaCompiler.Resolve(document, callNode, _views, _diagnostics);
                if (target is not null)
                {
                    Mapped(document, callNode.ArgumentSpan, "            await global::" + _namespace + ".Views." + SavannaCompiler.IdentifierPath(target.Name)
                                                            + ".RenderPartialAsync("     + writer     + ", (", callNode.Argument, "), " + context + ");");
                }
            }
            else
            {
                var comment = "__componentComment" + _temporary++;
                comments.Add((comment, callNode.Value, buildCondition));
                _code.Append("            await ").Append(writer).Append(".WriteLiteralAsync(").Append(comment).AppendLine(", Context.CancellationToken);");
                Mapped(document, callNode.ArgumentSpan, "            await " + context + ".RenderComponentAsync(" + writer + ", Context.GetComponent<" + callNode.Value + ">(), (", callNode.Argument, "));");
            }
        }

        _code.AppendLine("        }");
        foreach (var literal in literals)
        {
            // Literal buffers live outside the render method, so they need the same compilation guard as their use.
            if (literal.Condition.Length > 0)
            {
                _code.Append("#if ").AppendLine(literal.Condition);
            }

            _code.Append("        private static readonly byte[] ").Append(literal.Name).Append(" = ").Append(SymbolDisplay.FormatLiteral(literal.Text, true)).AppendLine("u8.ToArray();");
            if (literal.Condition.Length > 0)
            {
                _code.AppendLine("#endif");
            }
        }

        foreach (var comment in comments)
        {
            if (comment.Condition.Length > 0)
            {
                _code.Append("#if ").AppendLine(comment.Condition);
            }

            CommentField(comment.Name, SavannaComments.Component(comment.Type));
            if (comment.Condition.Length > 0)
            {
                _code.AppendLine("#endif");
            }
        }

        foreach (var attribute in attributes)
        {
            _code.Append("        private static readonly global::Serval.Savanna.SavannaAttributeName ").Append(attribute.Value)
                 .Append(" = new(").Append(SymbolDisplay.FormatLiteral(attribute.Key, true)).AppendLine(");");
        }
    }

    private void CommentField(string name, (string Brief, string Detailed) comment)
    {
        // The consuming project's symbols select one literal. The host environment never changes it at render time.
        _code.AppendLine("#if DEBUG");
        _code.Append("        private static readonly byte[] ").Append(name).Append(" = ").Append(SymbolDisplay.FormatLiteral(comment.Detailed, true)).AppendLine("u8.ToArray();");
        _code.AppendLine("#else");
        _code.Append("        private static readonly byte[] ").Append(name).Append(" = ").Append(SymbolDisplay.FormatLiteral(comment.Brief, true)).AppendLine("u8.ToArray();");
        _code.AppendLine("#endif");
    }

    private int FindBlock(int start, string name)
    {
        for (var index = start; index < _chain.Count; index++)
        {
            if (_chain[index].Blocks.Any(block => block.Name == name && !block.Required))
            {
                return index;
            }
        }

        return -1;
    }

    private void ValidateRenderedBody(SavannaDocument document, int documentIndex, IReadOnlyList<SavannaNode> nodes, string? blockName, SavannaHtmlContext html, SavannaHtmlControlFlow flow)
    {
        // Carry one HTML state through block substitutions so a child can't hide unsafe output inside a parent's textarea.
        for (var index = 0; index < nodes.Count; index++)
        {
            var node = nodes[index];
            flow.Visit(document, node, html, _diagnostics);
            if (node.Kind == SavannaNodeKind.Text)
            {
                html.Read(ReadText(nodes, ref index));
            }
            else if (node.Kind is SavannaNodeKind.Block or SavannaNodeKind.Parent)
            {
                var name     = node.Kind == SavannaNodeKind.Block ? node.Value : blockName!;
                var selected = FindBlock(node.Kind == SavannaNodeKind.Block ? 0 : documentIndex + 1, name);
                if (selected >= 0)
                {
                    var owner = _chain[selected];
                    ValidateRenderedBody(owner, selected, owner.Blocks.First(block => block.Name == name).Body, name, html, flow);
                }
            }
            else if (html.IsRcData && node.Kind is SavannaNodeKind.Html or SavannaNodeKind.Include or SavannaNodeKind.Component or SavannaNodeKind.Json or SavannaNodeKind.Slot)
            {
                _diagnostics.Add(new SavannaDiagnostic("SAVANNA003", "Rendered fragments and JSON cannot be placed inside title or textarea. Use an encoded expression.", document.Path, node.Span));
            }
        }
    }

    private void Mapped(SavannaDocument document, TextSpan span, string prefix, string expression, string suffix)
    {
        var start = document.Text.Lines.GetLinePosition(span.Start);
        var end   = document.Text.Lines.GetLinePosition(span.End);
        _code.Append("#line (").Append(start.Line + 1).Append(", ").Append(start.Character + 1).Append(") - (")
             .Append(end.Line                     + 1).Append(", ").Append(end.Character   + 1).Append(") ").Append(prefix.Length).Append(' ')
             .AppendLine(SymbolDisplay.FormatLiteral(document.Path.Replace('\\', '/'), true));
        _code.Append(prefix);
        var generatedStart = _code.Length;
        _code.Append(expression);
        _mappings.Add(new SavannaSourceMapping(document.Path, span, new TextSpan(generatedStart, expression.Length)));
        // A trailing C# line comment must not consume the generated punctuation.
        _code.AppendLine();
        _code.AppendLine(suffix).AppendLine("#line hidden");
    }

    private static string BlockMethod(int index, string name) => "__Block" + index + "_" + name.TrimStart('@') + "Async";

    private static bool IsFullAttribute(SavannaHtmlContext html, SavannaNode next) => html.IsEmptyQuotedValue
                                                                                && html.Interpolation is SavannaInterpolationContext.Attribute or SavannaInterpolationContext.Url
                                                                                && next.Kind == SavannaNodeKind.Text && next.Value.Length > 0 && next.Value[0] == html.Quote;

    private static string ReadText(IReadOnlyList<SavannaNode> nodes, ref int index)
    {
        var value = nodes[index].Value;
        if (index + 1 >= nodes.Count || nodes[index + 1].Kind != SavannaNodeKind.Text)
        {
            return value;
        }

        // Removing template comments can join parts of an HTML delimiter.
        var text = new StringBuilder(value);
        while (index + 1 < nodes.Count && nodes[index + 1].Kind == SavannaNodeKind.Text)
        {
            text.Append(nodes[++index].Value);
        }

        return text.ToString();
    }

    private static void ValidateBody(SavannaDocument document, IReadOnlyList<SavannaNode> nodes, List<SavannaDiagnostic> diagnostics)
    {
        var html = new SavannaHtmlContext();
        var flow = new SavannaHtmlControlFlow();
        for (var index = 0; index < nodes.Count; index++)
        {
            var node = nodes[index];
            flow.Visit(document, node, html, diagnostics);
            if (node.Kind == SavannaNodeKind.Text)
            {
                html.Read(ReadText(nodes, ref index));
                continue;
            }

            var allowed = node.Kind  == SavannaNodeKind.Expression
                ? html.Interpolation != SavannaInterpolationContext.Forbidden
                : html.IsText || html.IsRcData && node.Kind is not (SavannaNodeKind.Html or SavannaNodeKind.Include or SavannaNodeKind.Component or SavannaNodeKind.Json or SavannaNodeKind.Slot);
            if (node.Kind == SavannaNodeKind.Expression && html.Interpolation == SavannaInterpolationContext.Url)
            {
                // Validate the entire URL before writing it; concatenated fragments can change its scheme.
                allowed = html.IsEmptyQuotedValue && index + 1 < nodes.Count && nodes[index + 1].Kind         == SavannaNodeKind.Text
                          && nodes[index                                                    + 1].Value.Length > 0 && nodes[index + 1].Value[0] == html.Quote;
            }

            if (!allowed)
            {
                diagnostics.Add(new SavannaDiagnostic("SAVANNA003", "Savanna output is only allowed in HTML text or quoted safe attributes; control flow and rendered fragments require text context.", document.Path, node.Span));
            }
        }

        if (!html.IsText)
        {
            diagnostics.Add(new SavannaDiagnostic("SAVANNA003", "A view or block must finish outside HTML tags, comments, and executable text contexts.", document.Path, nodes.Count > 0 ? nodes[nodes.Count - 1].Span : default));
        }
    }
