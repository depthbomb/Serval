using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using System.Collections.Immutable;
using System.Text;
using System.Text.RegularExpressions;
using Serval.Routing;

namespace Serval.Generators;

/// <summary>Generates controller registration methods and reports invalid controller actions.</summary>
[Generator(LanguageNames.CSharp)]
public sealed class ControllerGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor InvalidController = new("SERVAL001", "Invalid controller", "Controller '{0}' must be a public, non-abstract, non-generic top-level class", "Serval", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor InvalidAction     = new("SERVAL002", "Invalid action", "Action '{0}' must be a public, non-generic instance method returning Task<IActionResult> or ValueTask<IActionResult> (including concrete results), with RequestContext, CancellationToken, or explicitly bound parameters", "Serval", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor InvalidRoute      = new("SERVAL003", "Invalid route", "Route '{0}' is invalid: {1}", "Serval", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor InvalidBinding    = new("SERVAL004", "Invalid action binding", "Action '{0}' has an invalid binding: {1}", "Serval", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor DuplicateRoute    = new("SERVAL005", "Duplicate route", "Route '{0}' conflicts with another route in this assembly: {1}", "Serval", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor InvalidUrlHelper  = new("SERVAL006", "Conflicting URL helper", "Route '{0}' cannot generate a URL helper: {1}", "Serval", DiagnosticSeverity.Error, true);

    /// <summary>Registers incremental discovery and emission for attributed controllers.</summary>
    /// <param name="context">The Roslyn initialization context.</param>
    /// <remarks>
    ///     Discovers ControllerAttribute classes and emits registration methods for the containing assembly.
    /// </remarks>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var controllers = context.SyntaxProvider.ForAttributeWithMetadataName("Serval.Routing.ControllerAttribute", static (node, _) => node is ClassDeclarationSyntax, static (syntax, _) => (INamedTypeSymbol)syntax.TargetSymbol).Collect();
        context.RegisterSourceOutput(controllers.Combine(context.CompilationProvider.Select(static (compilation, _) => compilation.AssemblyName ?? "Application")), static (output, input) => Emit(output, input.Left, input.Right));
    }

    internal static string Literal(string value) => SymbolDisplay.FormatLiteral(value, true);

    private static void Emit(SourceProductionContext context, ImmutableArray<INamedTypeSymbol> controllers, string assemblyName)
    {
        if (controllers.IsDefaultOrEmpty)
        {
            return;
        }

        var registrationName = "@" + new string([.. assemblyName.Select(character => character is >= 'a' and <= 'z' or >= 'A' and <= 'Z' or >= '0' and <= '9' ? character : '_')]) + "Controllers";
        var code = new StringBuilder($$"""
                                       // <auto-generated/>
                                       #nullable enable
                                       namespace Serval.Generated;

                                       internal static class ControllerRegistrationExtensions
                                       {
                                           extension(global::Serval.Hosting.ServalBuilder builder)
                                           {
                                               public global::Serval.Hosting.ServalBuilder AddGeneratedControllers() => {{registrationName}}.Register(builder);
                                           }
                                       }

                                       public static class {{registrationName}}
                                       {
                                           public static global::Serval.Hosting.ServalBuilder Register(global::Serval.Hosting.ServalBuilder builder)
                                           {
                                               global::System.ArgumentNullException.ThrowIfNull(builder);

                                       """);

        var helpers     = new StringBuilder("\ninternal static class RouteUrlExtensions\n{\n");
        var names       = new HashSet<string>(StringComparer.Ordinal);
        var signatures  = new HashSet<string>(StringComparer.Ordinal);
        var helperNames = new HashSet<string>(StringComparer.Ordinal);
        foreach (var controller in controllers.Distinct<INamedTypeSymbol>(SymbolEqualityComparer.Default).OrderBy(type => type.ToDisplayString(), StringComparer.Ordinal))
        {
            if (controller.IsAbstract || controller.IsStatic || controller.IsGenericType || controller.ContainingType is not null || controller.DeclaredAccessibility != Accessibility.Public)
            {
                context.ReportDiagnostic(Diagnostic.Create(InvalidController, controller.Locations.FirstOrDefault(), controller.Name));
                continue;
            }

            var controllerType       = controller.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var prefix               = controller.GetAttributes().FirstOrDefault(attribute => attribute.AttributeClass?.ToDisplayString() == "Serval.Routing.RouteAttribute")?.ConstructorArguments[0].Value as string ?? "";
            var controllerMiddleware = controller.GetAttributes().Where(IsMiddleware).Select(RenderAttribute).ToArray();
            foreach (var method in controller.GetMembers().OfType<IMethodSymbol>())
            {
                var routes = method.GetAttributes().Where(IsRoute).ToArray();
                if (routes.Length == 0)
                {
                    continue;
                }

                if (method.DeclaredAccessibility != Accessibility.Public || method.IsStatic || method.IsGenericMethod
                    || method.ReturnType is not INamedTypeSymbol { TypeArguments.Length: 1 } asyncReturn
                    || asyncReturn.ContainingNamespace.ToDisplayString() != "System.Threading.Tasks"
                    || asyncReturn.Name is not ("Task" or "ValueTask") || !IsActionResult(asyncReturn.TypeArguments[0])
                    || method.Parameters.Any(parameter => !IsSupportedParameter(parameter)))
                {
                    context.ReportDiagnostic(Diagnostic.Create(InvalidAction, method.Locations.FirstOrDefault(), method.Name));
                    continue;
                }

                var middleware = controllerMiddleware.Concat(method.GetAttributes().Where(IsMiddleware).Select(RenderAttribute)).ToArray();
                for (var index = 0; index < routes.Length; index++)
                {
                    context.CancellationToken.ThrowIfCancellationRequested();
                    var          route         = routes[index];
                    var          routeType     = route.AttributeClass!.Name;
                    var          verb          = routeType                                                                                     == "HttpRouteAttribute" ? (string)route.ConstructorArguments[0].Value! : routeType.Substring(0, routeType.Length - 9).ToUpperInvariant();
                    var          templateIndex = routeType                                                                                     == "HttpRouteAttribute" ? 1 : 0;
                    var          template      = route.ConstructorArguments.Length                                                             > templateIndex ? route.ConstructorArguments[templateIndex].Value as string ?? "" : "";
                    var          path          = template.StartsWith("~/", StringComparison.Ordinal) ? template.Substring(1) : template.Length == 0 ? "/" + prefix.TrimStart('/') : "/" + string.Join("/", new[] { prefix.Trim('/'), template.TrimStart('/') }.Where(part => part.Length > 0));
                    var          name          = route.NamedArguments.FirstOrDefault(pair => pair.Key == "Name").Value.Value as string ?? $"{controller.Name}.{method.Name}{(index == 0 ? "" : $".{index}")}";
                    var          location      = route.ApplicationSyntaxReference?.GetSyntax(context.CancellationToken).GetLocation()  ?? method.Locations.FirstOrDefault();
                    RoutePattern pattern;
                    try
                    {
                        if (string.IsNullOrWhiteSpace(verb))
                        {
                            throw new ArgumentException("The HTTP method cannot be empty.");
                        }

                        pattern = new RoutePattern(path);
                        ValidateConstraints(pattern);
                    }
                    catch (ArgumentException exception)
                    {
                        context.ReportDiagnostic(Diagnostic.Create(InvalidRoute, location, path, exception.Message));
                        continue;
                    }

                    // Only flag duplicates that conflict even with strict slashes and case-sensitive paths.
                    // The router still checks the complete registry with the application's actual options.
                    if (!names.Add(name) || !signatures.Add(verb.ToUpperInvariant() + " " + pattern.Signature(true, true)))
                    {
                        context.ReportDiagnostic(Diagnostic.Create(DuplicateRoute, location, path, "duplicate name or HTTP method/template"));
                        continue;
                    }

                    if (!BindingEmitter.TryCreate(method, pattern, out var binding, out var bindingError))
                    {
                        context.ReportDiagnostic(Diagnostic.Create(InvalidBinding, location, method.Name, bindingError));
                        continue;
                    }

                    var helper = UrlHelperEmitter.HelperName(name);
                    if (!helperNames.Add(helper) || !UrlHelperEmitter.HasUniqueParameters(pattern))
                    {
                        context.ReportDiagnostic(Diagnostic.Create(InvalidUrlHelper, location, name, "choose route and parameter names that remain distinct as C# identifiers"));
                        continue;
                    }

                    UrlHelperEmitter.Append(helpers, name, helper, pattern);
                    code.Append("        builder.AddController<").Append(controllerType).Append(">(").Append(Literal(verb)).Append(", ").Append(Literal(path)).Append(", ").Append(Literal(name)).Append(", ").Append(ActionLambda(method, asyncReturn, binding));
                    foreach (var attribute in middleware)
                    {
                        code.Append(", ").Append(attribute);
                    }

                    code.AppendLine(");");
                }
            }
        }

        code.AppendLine("        return builder;\n    }\n}");
        code.Append(helpers).AppendLine("}");
        context.AddSource("Serval.Controllers.g.cs", code.ToString());
    }

    private static bool IsRoute(AttributeData attribute) => attribute.AttributeClass?.ContainingNamespace.ToDisplayString() == "Serval.Routing" && attribute.AttributeClass.Name is "HttpRouteAttribute" or "GetAttribute" or "PostAttribute" or "PutAttribute" or "PatchAttribute" or "DeleteAttribute" or "HeadAttribute" or "OptionsAttribute";

    private static bool IsActionResult(ITypeSymbol type) => type.NullableAnnotation != NullableAnnotation.Annotated && (type.ToDisplayString() == "Serval.Http.IActionResult" || type.AllInterfaces.Any(contract => contract.ToDisplayString() == "Serval.Http.IActionResult"));

    private static bool IsSupportedParameter(IParameterSymbol parameter)
        => parameter.RefKind == RefKind.None && parameter.Type is not INamedTypeSymbol { IsRefLikeType: true }
                                             && parameter.Type.TypeKind is not (TypeKind.Pointer or TypeKind.FunctionPointer)
                                             && (parameter.Type.ToDisplayString() is "Serval.RequestContext" or "System.Threading.CancellationToken"
                                                 || parameter.GetAttributes().Any(BindingEmitter.IsBinding));

    private static bool IsMiddleware(AttributeData attribute)
    {
        for (var type = attribute.AttributeClass; type is not null; type = type.BaseType)
        {
            if (type.ToDisplayString() == "Serval.Middleware.MiddlewareAttribute")
            {
                return true;
            }
        }

        return false;
    }

    private static string RenderAttribute(AttributeData attribute)
    {
        var constructor = string.Join(", ", attribute.ConstructorArguments.Select(RenderConstant));
        var properties  = string.Join(", ", attribute.NamedArguments.Select(pair => $"@{pair.Key} = {RenderConstant(pair.Value)}"));
        return $"new {attribute.AttributeClass!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)}({constructor})" + (properties.Length > 0 ? $" {{ {properties} }}" : "");
    }

    private static string ActionLambda(IMethodSymbol method, INamedTypeSymbol returnType, BindingPlan binding)
    {
        var invocation   = $"controller.@{method.Name}({string.Join(", ", binding.Arguments)})";
        // Task<T> and ValueTask<T> aren't covariant. Concrete results need an awaited conversion too.
        var asynchronous = binding.ReadsBody || returnType.TypeArguments[0].ToDisplayString() != "Serval.Http.IActionResult";
        if (asynchronous)
        {
            invocation = "await " + invocation;
        }
        else if (returnType.Name == "Task")
        {
            invocation = $"new global::System.Threading.Tasks.ValueTask<global::Serval.Http.IActionResult>({invocation})";
        }

        var lambda = asynchronous ? "static async (controller, context) => " : "static (controller, context) => ";
        return binding.Statements.Count == 0
            ? lambda + invocation
            : lambda + "\n        {\n            " + string.Join("\n            ", binding.Statements) + "\n            return " + invocation + ";\n        }";
    }

    private static void ValidateConstraints(RoutePattern pattern)
    {
        foreach (var segment in pattern.Segments)
        {
            foreach (var expression in segment.Constraints)
            {
                // Custom predicates and case sensitivity come from runtime configuration. Validate defaults
                // against known constraints in the more permissive case-insensitive mode.
                var matches = RouteConstraintParser.Parse(expression, false, static (_, _) => static _ => true);
                try
                {
                    if (segment.Default is not null && !matches(segment.Default))
                    {
                        throw new ArgumentException($"Default value for '{segment.Name}' does not satisfy '{expression}'.");
                    }
                }
                catch (RegexMatchTimeoutException)
                {
                    // A build should not keep retrying an expensive user regex. Startup validation still applies.
                }
            }
        }
    }

    private static string RenderConstant(TypedConstant constant) => constant is { Kind: TypedConstantKind.Array, IsNull: false }
        ? $"new {constant.Type!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)} {{ {string.Join(", ", constant.Values.Select(RenderConstant))} }}"
        : constant.ToCSharpString();
}
