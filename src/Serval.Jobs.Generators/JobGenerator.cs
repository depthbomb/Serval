using System.Collections.Immutable;
using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Serval.Jobs.Generators;

/// <summary>Generates explicit job registration without runtime assembly scanning or attribute reflection.</summary>
[Generator(LanguageNames.CSharp)]
public sealed class JobGenerator : IIncrementalGenerator
{
    private const string PeriodicAttribute = "Serval.Jobs.PeriodicJobAttribute";
    private const string CronAttribute     = "Serval.Jobs.CronJobAttribute";

    private static readonly DiagnosticDescriptor InvalidJob      = new("SERVALJOB001", "Invalid job", "Job '{0}' must be a public, concrete, non-generic, non-file-local top-level class implementing Serval.Jobs.IJob", "Serval.Jobs", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor InvalidSchedule = new("SERVALJOB002", "Invalid job schedule", "Job '{0}' has an invalid schedule: {1}", "Serval.Jobs", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor DuplicateName   = new("SERVALJOB003", "Duplicate job name", "Job name '{0}' is already used in this assembly", "Serval.Jobs", DiagnosticSeverity.Error, true);

    /// <summary>Discovers periodic and cron job attributes and emits assembly-specific registration.</summary>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var periodic = context.SyntaxProvider.ForAttributeWithMetadataName(PeriodicAttribute, static (node, _) => node is TypeDeclarationSyntax, static (syntax, _) => (INamedTypeSymbol)syntax.TargetSymbol).Collect();
        var cron     = context.SyntaxProvider.ForAttributeWithMetadataName(CronAttribute, static (node,     _) => node is TypeDeclarationSyntax, static (syntax, _) => (INamedTypeSymbol)syntax.TargetSymbol).Collect();
        context.RegisterSourceOutput(periodic.Combine(cron).Combine(context.CompilationProvider), static (output, input) => Emit(output, input.Left.Left.AddRange(input.Left.Right), input.Right));
    }

    private static void Emit(SourceProductionContext context, ImmutableArray<INamedTypeSymbol> jobs, Compilation compilation)
    {
        if (jobs.IsDefaultOrEmpty)
        {
            return;
        }

        var identifier = new string([.. (compilation.AssemblyName ?? "Application").Select(character => character is >= 'a' and <= 'z' or >= 'A' and <= 'Z' or >= '0' and <= '9' ? character : '_')]);
        if (identifier.Length > 0 && char.IsDigit(identifier[0]))
        {
            identifier = "_" + identifier;
        }

        var registrationName = "@" + identifier + "Jobs";
        var code = new StringBuilder($$"""
                                       // <auto-generated/>
                                       #nullable enable
                                       namespace Serval.Generated;

                                       internal static class JobRegistrationExtensions
                                       {
                                           extension(global::Serval.Hosting.ServalBuilder builder)
                                           {
                                               public global::Serval.Hosting.ServalBuilder AddGeneratedJobs() => {{registrationName}}.Register(builder);
                                           }
                                       }

                                       public static class {{registrationName}}
                                       {
                                           public static global::Serval.Hosting.ServalBuilder Register(global::Serval.Hosting.ServalBuilder builder)
                                           {
                                               global::System.ArgumentNullException.ThrowIfNull(builder);
                                               global::Serval.Jobs.JobRegistration.Register(builder.Services,
                                               [
                                       """);
        var names = new HashSet<string>(StringComparer.Ordinal);
        foreach (var job in jobs.Distinct<INamedTypeSymbol>(SymbolEqualityComparer.Default).OrderBy(type => type.ToDisplayString(), StringComparer.Ordinal))
        {
            context.CancellationToken.ThrowIfCancellationRequested();
            var location = job.Locations.FirstOrDefault();
            if (job.TypeKind != TypeKind.Class    || job.IsAbstract || job.IsStatic || job.IsGenericType || job.IsFileLocal
                || job.ContainingType is not null || job.DeclaredAccessibility != Accessibility.Public
                || !job.AllInterfaces.Any(type => type.ToDisplayString() == "Serval.Jobs.IJob"))
            {
                context.ReportDiagnostic(Diagnostic.Create(InvalidJob, location, job.Name));
                continue;
            }

            var schedules = job.GetAttributes().Where(attribute => attribute.AttributeClass?.ToDisplayString() is PeriodicAttribute or CronAttribute).ToArray();
            if (schedules.Length != 1)
            {
                context.ReportDiagnostic(Diagnostic.Create(InvalidSchedule, location, job.Name, "declare exactly one periodic or cron attribute"));
                continue;
            }

            var schedule = schedules[0];
            location = schedule.ApplicationSyntaxReference?.GetSyntax(context.CancellationToken).GetLocation() ?? location;
            var name = NamedValue(schedule, "Name") as string ?? job.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat.WithMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.None));
            if (string.IsNullOrWhiteSpace(name))
            {
                context.ReportDiagnostic(Diagnostic.Create(InvalidSchedule, location, job.Name, "the name cannot be empty"));
                continue;
            }

            var expression = RenderSchedule(schedule, compilation, out var error);
            if (error is not null)
            {
                context.ReportDiagnostic(Diagnostic.Create(InvalidSchedule, location, job.Name, error));
                continue;
            }

            if (!names.Add(name))
            {
                context.ReportDiagnostic(Diagnostic.Create(DuplicateName, location, name));
                continue;
            }

            code.Append("            global::Serval.Jobs.JobRegistration.Create<").Append(job.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)).Append(">(").Append(expression).Append(", ").Append(Literal(name)).AppendLine("),");
        }

        code.AppendLine("        ]);\n        return builder;\n    }\n}");
        context.AddSource("Serval.Jobs.g.cs", code.ToString());
    }

    private static string? RenderSchedule(AttributeData attribute, Compilation compilation, out string? error)
    {
        error = null;
        if (attribute.ConstructorArguments.Length == 2)
        {
            return RenderMemberSchedule(attribute, compilation, out error);
        }

        var value = attribute.ConstructorArguments.FirstOrDefault().Value;
        if (attribute.AttributeClass?.ToDisplayString() == PeriodicAttribute)
        {
            if (value is not double milliseconds || double.IsNaN(milliseconds) || milliseconds is < 1 or > 4_294_967_294)
            {
                error = "the interval must be between 1 and 4,294,967,294 milliseconds";
                return null;
            }

            return "global::Serval.Jobs.JobSchedule.Every(global::System.TimeSpan.FromMilliseconds(" + milliseconds.ToString("R", CultureInfo.InvariantCulture) + "D))";
        }

        var zone    = NamedValue(attribute, "TimeZoneId") as string ?? "UTC";
        var options = NamedValue(attribute, "Options") is int flags ? flags : 0;
        if (value is not string expression || string.IsNullOrWhiteSpace(expression) || string.IsNullOrWhiteSpace(zone) || (options & ~15) != 0)
        {
            error = "supply a nonempty cron expression, time zone, and supported syntax options";
            return null;
        }

        // Cron parsing and platform time-zone lookup stay in the runtime package; there is one source of truth.
        return "global::Serval.Jobs.JobSchedule.Cron(" + Literal(expression) + ", global::System.TimeZoneInfo.FindSystemTimeZoneById(" + Literal(zone) + "), (global::Caprine.CronTimer.CronExpressionOptions)" + options.ToString(CultureInfo.InvariantCulture) + ")";
    }

    private static string? RenderMemberSchedule(AttributeData attribute, Compilation compilation, out string? error)
    {
        error = null;
        var periodic   = attribute.AttributeClass?.ToDisplayString() == PeriodicAttribute;
        var returnType = periodic ? "System.TimeSpan" : "Caprine.CronTimer.CronExpression";
        if (attribute.ConstructorArguments[0].Value is not INamedTypeSymbol { TypeKind: TypeKind.Class or TypeKind.Struct } type
            || !compilation.IsSymbolAccessibleWithin(type, compilation.Assembly)
            || attribute.ConstructorArguments[1].Value is not string name || string.IsNullOrWhiteSpace(name))
        {
            error = "supply an accessible schedule type and a nonempty member name";
            return null;
        }

        for (var containing = type; containing is not null; containing = containing.ContainingType)
        {
            if (containing.IsUnboundGenericType || containing.IsFileLocal)
            {
                error = "the schedule type must be closed and cannot be file-local";
                return null;
            }
        }

        // Partial declarations are visible here; Caprine's generators provide their implementations independently.
        var expected = compilation.GetTypeByMetadataName(returnType);
        var members = type.GetMembers(name).Where(member => member.IsStatic && !member.IsAbstract && compilation.IsSymbolAccessibleWithin(member, compilation.Assembly)).Where(member => member switch
        {
            IPropertySymbol { IsIndexer: false, SetMethod: null, ReturnsByRef: false, ReturnsByRefReadonly: false, GetMethod: {} getter } property
                => compilation.IsSymbolAccessibleWithin(getter, compilation.Assembly)
                   && SymbolEqualityComparer.Default.Equals(property.Type, expected),
            IMethodSymbol { MethodKind: MethodKind.Ordinary, IsGenericMethod: false, Parameters.Length: 0, ReturnsByRef: false, ReturnsByRefReadonly: false } method
                => SymbolEqualityComparer.Default.Equals(method.ReturnType, expected),
            _ => false,
        }).ToArray();
        if (members.Length != 1)
        {
            error = $"'{name}' must be an accessible static get-only property or non-generic parameterless method declared on the schedule type and returning {returnType} by value";
            return null;
        }

        var access = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + ".@" + members[0].Name + (members[0] is IMethodSymbol ? "()" : "");
        if (periodic)
        {
            return "global::Serval.Jobs.JobSchedule.Every(" + access + ")";
        }

        if (attribute.NamedArguments.Any(pair => pair.Key == "Options"))
        {
            error = "set cron syntax options on the referenced expression, not on CronJob";
            return null;
        }

        var zone = NamedValue(attribute, "TimeZoneId") as string ?? "UTC";
        if (string.IsNullOrWhiteSpace(zone))
        {
            error = "supply a nonempty time zone";
            return null;
        }

        return "global::Serval.Jobs.JobSchedule.Cron(" + access + ", global::System.TimeZoneInfo.FindSystemTimeZoneById(" + Literal(zone) + "))";
    }

    private static object? NamedValue(AttributeData attribute, string name) => attribute.NamedArguments.FirstOrDefault(pair => pair.Key == name).Value.Value;

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, true);
}
